// Builds stop-access.js: what is known about tactile guidance and spoken information at each stop edge,
// for blind and low-vision travellers (Settings › Blind or low vision; index.html "Where to stand").
//
//   node tools/build-stop-access.mjs
//
// From data/bern-stop-accessibility.json (tools/build-bern-accessibility.mjs: ATLAS accessibility data per stop
// edge from opentransportdata.swiss, so far for Bern). Only what the data says is there is kept; an edge
// without any of it is left out, so the app claims nothing it does not know.
//
// Per stop number (UIC): edges as [lon × 1e5, lat × 1e5, label, flags]. The app finds a journey's edge by its
// position (many bus stops have no signed label), else by its label ("7", "C"; "01" is written "1" as in the app).
//   t  tactile guide lines on the platform            (tactile_system)
//   f  tactile attention field at the boarding point  (attention_field)
//   a  spoken announcements                           (dynamic_audio, or info ACOUSTIC_INFORMATION)
//   s  departure display with speech output           (info TEXT_TO_SPEECH_*)
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../data/bern-stop-accessibility.json', import.meta.url), 'utf8'));
const stops = {};
let edges = 0;
for (const stop of src.stops) {
  const kept = [];
  for (const e of stop.edges) {
    const a = e.access || {}, info = a.info || [];
    const flags = (a.tactile_system === true ? 't' : '') + (a.attention_field === true ? 'f' : '')
      + (a.dynamic_audio === true || info.includes('ACOUSTIC_INFORMATION') ? 'a' : '')
      + (info.some((x) => x.startsWith('TEXT_TO_SPEECH')) ? 's' : '');
    if (!flags) continue;
    const label = String(e.label || '').trim().toUpperCase().replace(/^0+(?=\d)/, '');
    const at = Number.isFinite(e.lon) && Number.isFinite(e.lat) ? [Math.round(e.lon * 1e5), Math.round(e.lat * 1e5)] : [0, 0];
    kept.push([...at, label, flags]);
  }
  if (!kept.length) continue;
  stops[String(stop.didok)] = kept;
  edges += kept.length;
}
const out = `// Generated by tools/build-stop-access.mjs from data/bern-stop-accessibility.json (${src.generated}). Do not edit by hand.
// Source: opentransportdata.swiss, ATLAS accessibility data per stop edge (Bern).
// Per stop number: [lon × 1e5, lat × 1e5, label, flags]. Flags: t tactile guide lines, f tactile attention field
// at the boarding point, a spoken announcements, s departure display with speech output.
window.STOP_ACCESS = ${JSON.stringify({ generated: src.generated, stops })};
`;
writeFileSync(new URL('../stop-access.js', import.meta.url), out);
console.log(`stop-access.js: ${Object.keys(stops).length} stops, ${edges} edges, ${(out.length / 1024).toFixed(1)} kB`);
